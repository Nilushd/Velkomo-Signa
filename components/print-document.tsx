import QRCode from "qrcode";
import { headerLogo, LOGO_HEIGHT, type Field, type FormRow, type Theme } from "@/lib/types";
import { formatValue, fileRefs, fmtDate } from "@/lib/format";
import { FONT_STACKS } from "./form-renderer";
import { PrintToolbar } from "./print-toolbar";
import type { Detail } from "@/lib/submission-view";

async function qrSvg(text: string) {
  return QRCode.toString(text, { type: "svg", margin: 0, errorCorrectionLevel: "M", color: { dark: "#0F172A", light: "#FFFFFF" } });
}

const STAMP: Record<string, { label: string; color: string }> = {
  approved: { label: "APPROVED", color: "#047857" },
  pending: { label: "PENDING APPROVAL", color: "#B45309" },
  rejected: { label: "REJECTED", color: "#B91C1C" },
  withdrawn: { label: "WITHDRAWN", color: "#52525B" },
};

function Header({ theme, title, propertyName, propertyLogo, right }: { theme: Theme; title: string; propertyName: string; propertyLogo: string | null; right: React.ReactNode }) {
  const logo = headerLogo(theme, propertyLogo);
  const align = theme.logoAlign ?? "left";
  return (
    <header className="flex items-start gap-6 border-b-2 pb-4" style={{ borderColor: theme.primary || "#2563EB" }}>
      <div className={`flex min-w-0 flex-1 flex-col gap-1.5 ${align === "center" ? "items-center text-center" : align === "right" ? "items-end text-right" : "items-start"}`}>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        {logo && <img src={`/api/files/${logo}`} alt="" style={{ height: LOGO_HEIGHT[theme.logoSize ?? "m"] }} className="w-auto max-w-[240px] object-contain" />}
        {(theme.showPropertyName || !logo) && <p className="text-sm font-semibold uppercase tracking-wide text-ink-soft">{propertyName}</p>}
        <h1 className="text-[22px] font-bold leading-tight text-ink" style={{ fontFamily: "inherit" }}>{title}</h1>
        {theme.formCode && <p className="font-mono text-[11px] text-ink-mute">{theme.formCode}</p>}
      </div>
      {right}
    </header>
  );
}

function Footer({ theme, children }: { theme: Theme; children?: React.ReactNode }) {
  return (
    <footer className="avoid-break mt-6 space-y-1 border-t border-ink-line pt-3 text-[10px] leading-snug text-ink-mute">
      {children}
      {theme.printFooter && <p className="whitespace-pre-line text-ink-soft">{theme.printFooter}</p>}
      <p>Generated by Velkomo Signa</p>
    </footer>
  );
}

function AnswerValue({ f, v }: { f: Field; v: unknown }) {
  if (f.type === "signature") {
    // eslint-disable-next-line @next/next/no-img-element
    return typeof v === "string" && v ? <img src={v} alt="Signature" className="h-14 w-auto" /> : <span className="text-ink-mute">—</span>;
  }
  if (f.type === "file") {
    const refs = fileRefs(v);
    return refs.length ? <ul>{refs.map((r) => <li key={r.fileId}>📎 {r.name} <span className="text-ink-mute">({Math.max(1, Math.round(r.size / 1024))} KB)</span></li>)}</ul> : <span className="text-ink-mute">—</span>;
  }
  const s = formatValue(f, v);
  return s ? <span className="whitespace-pre-line">{s}</span> : <span className="text-ink-mute">—</span>;
}

/** A filled, approved (or pending) document with its approval record and verification QR. */
export async function PrintDocument({ d, propertyName, propertyLogo, verifyUrl, verifyPage, fingerprint, printedBy, backHref, toolbar = true, pdfHref }:
  { d: Detail; propertyName: string; propertyLogo: string | null; verifyUrl: string; verifyPage: string; fingerprint: string; printedBy: string; backHref: string; toolbar?: boolean; pdfHref?: string }) {
  const { sub, form } = d;
  const theme = form.theme;
  const qr = await qrSvg(verifyUrl);
  const stamp = STAMP[sub.status] ?? STAMP.pending;
  const decisions = d.approvals.filter((a) => a.version === sub.version && (a.decision === "approved" || a.decision === "rejected"));
  const waiting = d.approvals.filter((a) => a.version === sub.version && a.decision === "pending" && sub.status === "pending");
  const lastDecision = decisions.at(-1);
  return (
    <div className={toolbar ? "min-h-screen bg-ink-wash py-6 print:bg-white print:py-0" : "print-batch-item bg-ink-wash pb-6 print:bg-white print:pb-0"} style={{ fontFamily: FONT_STACKS[theme.font ?? "sans"] }}>
      {toolbar && <PrintToolbar backHref={backHref} pdfHref={pdfHref} />}
      <article className="print-sheet mx-auto max-w-[210mm] bg-white p-[12mm] text-[12.5px] text-ink shadow-card">
        <Header theme={theme} title={form.title} propertyName={propertyName} propertyLogo={propertyLogo} right={
          <div className="flex shrink-0 items-start gap-3">
            <div className="text-right text-[11px] leading-relaxed">
              <p className="text-ink-mute">Document No.</p>
              <p className="font-mono text-[15px] font-bold">{sub.ref_no}</p>
              {sub.version > 1 && <p className="font-mono">Version {sub.version}</p>}
              <p className="mt-1 text-ink-mute">Verification code</p>
              <p className="font-mono font-semibold tracking-wide">{sub.verify_code}</p>
            </div>
            <div className="h-[92px] w-[92px]" dangerouslySetInnerHTML={{ __html: qr }} aria-label="Verification QR code" />
          </div>} />

        <section className="mt-4 flex flex-wrap items-center justify-between gap-3">
          <dl className="grid grid-cols-[auto_1fr] gap-x-4 gap-y-0.5 text-[12px]">
            <dt className="text-ink-mute">Submitted by</dt><dd className="font-medium">{sub.submitter}</dd>
            <dt className="text-ink-mute">Submitted on</dt><dd>{fmtDate(sub.created_at)}</dd>
            {sub.version > 1 && <><dt className="text-ink-mute">Last revised</dt><dd>{fmtDate(sub.updated_at)}</dd></>}
          </dl>
          <div className="rotate-[-3deg] rounded-md border-[3px] px-4 py-1.5 text-center font-bold tracking-widest" style={{ color: stamp.color, borderColor: stamp.color }}>
            <p className="text-[15px]">{stamp.label}</p>
            {lastDecision && sub.status !== "pending" && <p className="text-[10px] font-semibold tracking-normal">{fmtDate(lastDecision.decided_at, false)}</p>}
          </div>
        </section>

        <section className="mt-4">
          <table className="w-full border-collapse text-[12.5px]">
            <tbody>
              {form.schema.map((f) => f.type === "heading" ? (
                <tr key={f.id} className="avoid-break"><td colSpan={2} className="pb-1 pt-4 text-[13px] font-bold" style={{ color: theme.primary || "#2563EB" }}>{f.label}</td></tr>
              ) : (
                <tr key={f.id} className="avoid-break border-b border-ink-line/70 align-top">
                  <th className="w-[36%] py-1.5 pr-3 text-left font-medium text-ink-soft">{f.label}</th>
                  <td className="py-1.5"><AnswerValue f={f} v={sub.data[f.id]} /></td>
                </tr>))}
            </tbody>
          </table>
        </section>

        <section className="avoid-break mt-6">
          <h2 className="mb-2 text-[13px] font-bold uppercase tracking-wide text-ink-soft">Approval record</h2>
          {d.steps.length === 0 ? <p className="text-ink-mute">No approval levels — accepted automatically on submission.</p> : (
            <table className="w-full border-collapse text-[12px]">
              <thead><tr className="border-b-2 border-ink-line text-left text-[11px] uppercase tracking-wide text-ink-mute">
                <th className="py-1 pr-2">Level</th><th className="py-1 pr-2">Approver</th><th className="py-1 pr-2">Decision</th><th className="py-1 pr-2">Date &amp; time</th><th className="py-1">Comment</th></tr></thead>
              <tbody>
                {d.steps.map((s) => {
                  const dec = decisions.find((a) => a.level === s.level);
                  const wait = waiting.filter((a) => a.level === s.level);
                  return (
                    <tr key={s.level} className="border-b border-ink-line/70 align-top">
                      <td className="py-1.5 pr-2"><b>{s.level}</b> · {s.name}</td>
                      <td className="py-1.5 pr-2">{dec ? dec.approver : wait.length ? wait.map((w) => w.approver).join(" / ") : "—"}</td>
                      <td className="py-1.5 pr-2 font-semibold" style={{ color: dec?.decision === "approved" ? "#047857" : dec?.decision === "rejected" ? "#B91C1C" : "#B45309" }}>
                        {dec ? (dec.decision === "approved" ? "Approved" : "Rejected") : wait.length ? "Waiting" : sub.status === "approved" ? "—" : "Not reached"}</td>
                      <td className="whitespace-nowrap py-1.5 pr-2">{dec ? fmtDate(dec.decided_at) : ""}</td>
                      <td className="py-1.5">{dec?.comment ?? ""}</td>
                    </tr>);
                })}
              </tbody>
            </table>)}
          {d.versions.length > 0 && <p className="mt-2 text-[11px] text-ink-mute">This request was revised {d.versions.length} time{d.versions.length > 1 ? "s" : ""}; earlier versions and decisions are kept in the system history.</p>}
        </section>

        <Footer theme={theme}>
          <p className="text-[11px] text-ink-soft"><b>Verify this document:</b> scan the QR code, or open <span className="font-mono">{verifyPage}</span> and enter document number <b className="font-mono">{sub.ref_no}</b> with verification code <b className="font-mono">{sub.verify_code}</b>.</p>
          <p>Content fingerprint <span className="font-mono">{fingerprint}</span> · Printed {fmtDate(new Date())} by {printedBy}</p>
        </Footer>
      </article>
    </div>
  );
}

function BlankField({ f }: { f: Field }) {
  const line = <div className="h-6 border-b border-ink" />;
  switch (f.type) {
    case "textarea": return <div className="space-y-4 pt-1">{line}{line}{line}</div>;
    case "date": return <p className="pt-1 font-mono tracking-widest text-ink-soft">____ / ____ / ________</p>;
    case "select": case "radio": case "checkbox":
      return f.options?.length
        ? <div className="flex flex-wrap gap-x-5 gap-y-1 pt-1">{f.options.map((o) => <span key={o} className="inline-flex items-center gap-1.5"><span className="inline-block h-3.5 w-3.5 border border-ink" style={{ borderRadius: f.type === "radio" ? 999 : 2 }} />{o}</span>)}</div>
        : <span className="inline-block h-3.5 w-3.5 border border-ink" />;
    case "signature": return <div className="mt-1 h-16 rounded border border-ink/70" />;
    case "file": return <p className="pt-1 text-ink-soft">☐ Documents attached ({f.multiple ? `up to ${f.maxFiles || 5}` : "1"}): ________________________________</p>;
    default: return line;
  }
}

/** Blank form for filling by hand, with a QR to fill it online instead and sign-off boxes for each approval level. */
export async function PrintBlank({ form, propertyName, propertyLogo, fillUrl, steps, backHref }:
  { form: FormRow; propertyName: string; propertyLogo: string | null; fillUrl: string; steps: { level: number; name: string }[]; backHref: string }) {
  const theme = form.theme;
  const qr = await qrSvg(fillUrl);
  return (
    <div className="min-h-screen bg-ink-wash py-6 print:bg-white print:py-0" style={{ fontFamily: FONT_STACKS[theme.font ?? "sans"] }}>
      <PrintToolbar backHref={backHref} />
      <article className="print-sheet mx-auto max-w-[210mm] bg-white p-[12mm] text-[12.5px] text-ink shadow-card">
        <Header theme={theme} title={form.title} propertyName={propertyName} propertyLogo={propertyLogo} right={
          <div className="flex shrink-0 items-start gap-3">
            <div className="text-right text-[11px] leading-relaxed">
              <p className="text-ink-mute">Document No.</p>
              <p className="font-mono text-[13px]">REQ-________</p>
              <p className="mt-2 max-w-[110px] text-ink-mute">Scan to fill in online instead</p>
            </div>
            <div className="h-[92px] w-[92px]" dangerouslySetInnerHTML={{ __html: qr }} aria-label="QR code to fill online" />
          </div>} />
        {form.description && <p className="mt-3 whitespace-pre-line text-ink-soft">{form.description}</p>}
        <section className="mt-4 space-y-3">
          {form.schema.map((f) => f.type === "heading"
            ? <h2 key={f.id} className="avoid-break pt-3 text-[13px] font-bold" style={{ color: theme.primary || "#2563EB" }}>{f.label}</h2>
            : <div key={f.id} className="avoid-break"><p className="font-medium text-ink-soft">{f.label}{f.required && <span className="text-red-600"> *</span>}</p>{f.help && <p className="text-[10.5px] text-ink-mute">{f.help}</p>}<BlankField f={f} /></div>)}
        </section>
        {steps.length > 0 && (
          <section className="avoid-break mt-6">
            <h2 className="mb-2 text-[13px] font-bold uppercase tracking-wide text-ink-soft">Approval</h2>
            <table className="w-full border-collapse text-[12px]">
              <thead><tr className="text-left text-[11px] uppercase tracking-wide text-ink-mute"><th className="border border-ink-line p-1.5">Level</th><th className="border border-ink-line p-1.5">Name</th><th className="border border-ink-line p-1.5">Approved / Rejected</th><th className="border border-ink-line p-1.5">Signature</th><th className="border border-ink-line p-1.5">Date</th></tr></thead>
              <tbody>{steps.map((s) => <tr key={s.level}><td className="border border-ink-line p-1.5">{s.level} · {s.name}</td><td className="h-11 border border-ink-line p-1.5" /><td className="border border-ink-line p-1.5">☐ Approved ☐ Rejected</td><td className="border border-ink-line p-1.5" /><td className="border border-ink-line p-1.5" /></tr>)}</tbody>
            </table>
          </section>)}
        <Footer theme={theme}><p className="text-[11px] text-ink-soft">Fill in online: <span className="font-mono">{fillUrl}</span></p></Footer>
      </article>
    </div>
  );
}
